import * as DropdownMenuPrimitive from '@radix-ui/react-dropdown-menu'
import { Circle } from 'lucide-react'
import * as React from 'react'

import { CheckIcon, ChevronRightIcon } from '@radix-ui/react-icons'
import { useCombineRefs } from '../hooks/useCombineRefs'
import { cn } from './utils'

const PortalContainerContext = React.createContext<HTMLElement | null>(null)
const SetPortalContainerContext = React.createContext<React.Dispatch<HTMLElement | null>>(() => {})

const DropdownMenu: typeof DropdownMenuPrimitive.Root = props => {
  const [portalContainer, setPortalContainer] = React.useState<HTMLElement | null>(null)
  return (
    <PortalContainerContext.Provider value={portalContainer}>
      <SetPortalContainerContext.Provider value={setPortalContainer}>
        <DropdownMenuPrimitive.Root {...props} />
      </SetPortalContainerContext.Provider>
    </PortalContainerContext.Provider>
  )
}

const DropdownMenuTrigger = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.Trigger>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.Trigger>
>((props, ref) => {
  const setPortalContainer = React.useContext(SetPortalContainerContext)
  const combineRefs = useCombineRefs(ref, setPortalContainer)
  return <DropdownMenuPrimitive.Trigger ref={combineRefs()} {...props} />
})

const DropdownMenuGroup = DropdownMenuPrimitive.Group

const DropdownMenuPortal: typeof DropdownMenuPrimitive.Portal = ({ container, ...otherProps }) => {
  const portalContainer = React.useContext(PortalContainerContext)
  return <DropdownMenuPrimitive.Portal {...otherProps} container={container || portalContainer || null} />
}

const DropdownMenuSub = DropdownMenuPrimitive.Sub

const DropdownMenuRadioGroup = DropdownMenuPrimitive.RadioGroup

const DropdownMenuSubTrigger = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.SubTrigger>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.SubTrigger> & {
    inset?: boolean
  }
>(({ className, inset, children, ...props }, ref) => (
  <DropdownMenuPrimitive.SubTrigger
    ref={ref}
    className={cn(
      'focus:bg-accent data-[state=open]:bg-accent flex cursor-default select-none items-center rounded-sm px-2 py-1.5 text-sm outline-none',
      inset && 'pl-8',
      className
    )}
    {...props}
  >
    {children}
    <ChevronRightIcon className="size-4 ml-auto" />
  </DropdownMenuPrimitive.SubTrigger>
))
DropdownMenuSubTrigger.displayName = DropdownMenuPrimitive.SubTrigger.displayName

const DropdownMenuSubContent = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.SubContent>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.SubContent>
>(({ className, ...props }, ref) => (
  <DropdownMenuPrimitive.SubContent
    ref={ref}
    className={cn(
      'bg-popover text-popover-foreground data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 z-50 min-w-[8rem] overflow-hidden rounded-md border p-1 shadow-lg',
      className
    )}
    {...props}
  />
))
DropdownMenuSubContent.displayName = DropdownMenuPrimitive.SubContent.displayName

const DropdownMenuContent = React.forwardRef<
  React.ElementRef<typeof DropdownMenuPrimitive.Content>,
  React.ComponentPropsWithoutRef<typeof DropdownMenuPrimitive.Content> & { container?: HTMLElement | null }
>(({ container = window.document.body, className, sideOffset = 4, ...props }, ref) => {
  const portalContainer = React.useContext(PortalContainerContext)
  return (
    <DropdownMenuPrimitive.Portal container={container || portalContainer || null}>
      <DropdownMenuPrimitive.Content
        ref={ref}
        sideOffset={sideOffset}
        className={cn(
          'bg-popover text-popover-foreground data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2 z-50 min-w-[8rem] overflow-hidden rounded-md border p-1 shadow-md',
          className
        )}
        {...props}
      />
    </DropdownMenuPrimitive.Portal>
  )
})
DropdownMenuContent.displayName = DropdownMenuPrimitive.Content.displayName

