const MenubarPortal: typeof MenubarPrimitive.Portal = ({ container, ...otherProps }) => {
  const portalContainer = React.useContext(PortalContainerContext)
  return <MenubarPrimitive.Portal {...otherProps} container={container || portalContainer || null} />
}

